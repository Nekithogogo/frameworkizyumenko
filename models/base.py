"""Базовый класс объектов предметной области."""


class Entity:
    """Объект предметной области с уникальным идентификатором.

    Наследники обязаны переопределить метод to_dict(): по нему
    хранилище единообразно сохраняет объекты любых классов
    (полиморфизм).
    """

    def __init__(self, entity_id: int) -> None:
        """Сохранить идентификатор объекта."""
        self.id = entity_id

    def to_dict(self) -> dict:
        """Вернуть данные объекта для сохранения в JSON."""
        raise NotImplementedError(
            f"{type(self).__name__} должен реализовать to_dict()"
        )

    def __repr__(self) -> str:
        """Вернуть отладочное представление объекта."""
        return f"{type(self).__name__}(id={self.id})"
